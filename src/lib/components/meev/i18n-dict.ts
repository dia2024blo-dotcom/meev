/** The interest's label in the active language (key → AR map, dict → fr/es/tr/de, fallback EN). */
export function interestLabel(key: string, label: string, lang: string): string {
  if (lang === "ar") return INTEREST_AR[key] ?? label
  if (isExtraLang(lang)) return EXTRA_TRANSLATIONS[lang][label] ?? label
  return label
}
